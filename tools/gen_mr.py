"""Regenerates app/src/main/java/tachiyomi/i18n/MR.kt from Mihon's English strings for the keys the code uses."""
import glob, html, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "app/src/main/java")
M = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/Projects/ref/mihon") + "/i18n/src/commonMain/moko-resources/base/"
used_s, used_p = set(), set()
for f in glob.glob(D + "/**/*.kt", recursive=True):
    if f.endswith("tachiyomi/i18n/MR.kt"): continue
    t = open(f).read()
    used_s |= set(re.findall(r'MR\.strings\.([a-zA-Z0-9_]+)', t)); used_p |= set(re.findall(r'MR\.plurals\.([a-zA-Z0-9_]+)', t))
strings = dict(re.findall(r'<string name="([^"]+)"[^>]*>(.*?)</string>', open(M + "strings.xml").read(), re.S))
plur = {}
for name, body in re.findall(r'<plurals name="([^"]+)">(.*?)</plurals>', open(M + "plurals.xml").read(), re.S):
    items = dict(re.findall(r'<item quantity="(\w+)">(.*?)</item>', body, re.S)); plur[name] = (items.get("one", items.get("other")), items.get("other"))
def lit(v): return json.dumps(html.unescape(v)).replace("$", "\\$")
out = ["// Generated by tools/gen_mr.py from Mihon's English strings (Apache-2.0).", "package tachiyomi.i18n", "",
       "import dev.icerock.moko.resources.PluralsResource", "import dev.icerock.moko.resources.StringResource", "",
       "object MR {", "    object strings {"]
missing = []
for n in sorted(used_s):
    if n not in strings: missing.append(n); continue
    out.append(f"        val {n} = StringResource({lit(strings[n])})")
out += ["    }", "", "    object plurals {"]
for n in sorted(used_p):
    if n not in plur: missing.append(n); continue
    o, ot = plur[n]; out.append(f"        val {n} = PluralsResource({lit(o)}, {lit(ot)})")
out += ["    }", "}"]
open(D + "/tachiyomi/i18n/MR.kt", "w").write("\n".join(out) + "\n")
print(len(used_s), "strings,", len(used_p), "plurals; missing:", missing)
